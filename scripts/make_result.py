#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""把分段、译文、术语表、核验结果合成 result.json + bilingual.md + glossary.csv。

用法:
    python3 make_result.py --case-json /input/case.json \
        --segments work/segments.json --translations work/translations.json \
        --glossary work/glossary.csv --checks work/checks.json \
        --out /app/output/result.json [--status auto|success|partial|failed|stuck]
"""
import argparse
import csv
import json
import os
import sys
from datetime import datetime, timezone


def load_json(path, default=None):
    if not path or not os.path.exists(path):
        return default
    with open(path, "r", encoding="utf-8-sig") as f:
        return json.load(f)


def load_glossary(path):
    rows = []
    if not path or not os.path.exists(path):
        return rows
    with open(path, "r", encoding="utf-8-sig", newline="") as f:
        for r in csv.DictReader(f):
            t = (r.get("term") or "").strip()
            if not t:
                continue
            rows.append({
                "term": t,
                "translation": (r.get("translation") or "").strip(),
                "locked": str(r.get("locked", "")).lower() in ("1", "true", "yes"),
                "note": (r.get("note") or "").strip(),
                "occurrences": [{"segment_id": r.get("first_segment", ""),
                                 "page": int(r["first_page"]) if str(r.get("first_page", "")).isdigit() else None}],
            })
    return rows


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--case-json", default=None)
    ap.add_argument("--segments", required=True)
    ap.add_argument("--translations", required=True)
    ap.add_argument("--glossary", default=None)
    ap.add_argument("--checks", default=None)
    ap.add_argument("--out", required=True)
    ap.add_argument("--status", default="auto")
    ap.add_argument("--out-dir", default=None, help="bilingual.md / glossary.csv 输出目录")
    args = ap.parse_args()

    case = load_json(args.case_json, {}) or {}
    segdata = load_json(args.segments, {}) or {}
    segs = segdata.get("segments", [])
    doc = segdata.get("doc", {})
    trans = load_json(args.translations, {}) or {}
    checks = load_json(args.checks, {}) or {}
    gloss = load_glossary(args.glossary)

    out_dir = args.out_dir or os.path.dirname(os.path.abspath(args.out))
    os.makedirs(out_dir, exist_ok=True)

    segments, untranslated = [], []
    for s in segs:
        if s.get("section") == "References":
            continue
        tr = trans.get(s.get("id"))
        if not tr:
            untranslated.append({"segment_id": s["id"], "reason": "未翻译(预算或解析失败)"})
            continue
        terms = [g["term"] for g in gloss if g["term"].lower() in s.get("source", "").lower()]
        segments.append({
            "id": s["id"],
            "section": s.get("section", ""),
            "page": s.get("page"),
            "source": s.get("source", ""),
            "translation": tr,
            "terms": terms,
            "confidence": "medium" if any(k in tr for k in ("【存疑", "【原文残缺")) else "high",
            "note": "",
        })

    cov = checks.get("coverage", {})
    hard_fail = bool(untranslated) or bool(cov.get("missing"))
    soft_fail = any(not checks.get(k, {}).get("ok", True)
                    for k in ("numbers", "units", "citations", "formulas", "figures_tables", "negation"))
    term_rate = checks.get("term_consistency", {}).get("rate", 1.0)

    if args.status != "auto":
        status = args.status
    elif not segments:
        status = "failed"
    elif hard_fail:
        status = "partial"
    elif soft_fail or term_rate < 1.0:
        status = "partial"
    else:
        status = "success"

    result = {
        "case_id": case.get("case_id") or case.get("id") or "unknown",
        "status": status,
        "language": {"source": doc.get("lang", "en"), "target": "zh"},
        "document": {
            "title": case.get("title") or doc.get("source_file", ""),
            "pages": doc.get("pages", 0),
            "source_file": doc.get("source_file", ""),
            "has_text_layer": True,
        },
        "glossary": gloss,
        "segments": segments,
        "checks": {k: checks.get(k, {"ok": True, "issues": []})
                   for k in ("numbers", "units", "citations", "formulas",
                             "figures_tables", "negation", "term_consistency")},
        "untranslated": untranslated,
        "uncertainties": [],
        "artifacts": [{"path": "bilingual.md", "kind": "markdown"},
                      {"path": "glossary.csv", "kind": "csv"}],
        "run": {"tool_versions": {"python": sys.version.split()[0]},
                "notes": "generated by literature-translation-bilingual skill",
                "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds")},
    }
    if term_rate < 1.0:
        result["uncertainties"].append({
            "segment_id": ",".join(sorted({v["segment_id"] for v in
                                           checks.get("term_consistency", {}).get("violations", [])})),
            "issue": "术语一致率 %.3f < 1.0" % term_rate,
            "why": "锁定译名未在全部命中段落出现",
            "suggested_action": "回改违例段落, 或确认该术语是否应拆分为不同义项",
        })
    for k in ("numbers", "units", "citations", "formulas", "figures_tables", "negation"):
        if not checks.get(k, {}).get("ok", True):
            result["uncertainties"].append({
                "segment_id": "",
                "issue": "%s 核验未通过" % k,
                "why": "见 checks.%s.issues" % k,
                "suggested_action": "逐条回改后重跑 check_translation.py",
            })

    with open(args.out, "w", encoding="utf-8") as f:
        json.dump(result, f, ensure_ascii=False, indent=1)

    md = ["# 双语对照（%s）" % result["case_id"], "",
          "> 段号 pXXX 与原文段落一一对应；页码为抽取文本时的页序。", ""]
    for s in segments:
        md.append("## %s ｜ %s ｜ p.%s" % (s["id"], s["section"], s["page"]))
        md.append("")
        md.append("**原文**：" + s["source"])
        md.append("")
        md.append("**译文**：" + s["translation"])
        md.append("")
    with open(os.path.join(out_dir, "bilingual.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(md))

    if args.glossary and os.path.exists(args.glossary):
        with open(args.glossary, "r", encoding="utf-8-sig", newline="") as f:
            raw = f.read()
        with open(os.path.join(out_dir, "glossary.csv"), "w", encoding="utf-8-sig", newline="") as f:
            f.write(raw)

    print(json.dumps({"status": "ok", "out": args.out, "case_status": status,
                      "segments": len(segments), "untranslated": len(untranslated),
                      "term_rate": term_rate}, ensure_ascii=False))


if __name__ == "__main__":
    sys.exit(main())

